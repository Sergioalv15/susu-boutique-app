create or replace function public.is_business_member(target_business_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.business_members as member
    where member.business_id = target_business_id
      and member.user_id = (select auth.uid())
  );
$$;

revoke all on function public.is_business_member(uuid) from public;
grant execute on function public.is_business_member(uuid) to authenticated;

create table public.daily_records (
  business_id uuid not null references public.businesses(id) on delete cascade,
  date date not null,
  total_sold numeric(12, 2) not null default 0,
  investment_cost numeric(12, 2) not null default 0,
  additional_expenses numeric(12, 2) not null default 0,
  profit_percent numeric(5, 4) not null default 0.3 check (profit_percent between 0 and 1),
  net_profit numeric(12, 2) not null default 0,
  notes text not null default '',
  dataphone_sales numeric(12, 2) not null default 0,
  created_at timestamptz not null default now(),
  primary key (business_id, date)
);

create index daily_records_business_date_idx
  on public.daily_records (business_id, date desc);

create table public.suppliers (
  id bigint generated by default as identity primary key,
  business_id uuid not null references public.businesses(id) on delete cascade,
  name text not null,
  phone text not null default '',
  notes text not null default '',
  created_at timestamptz not null default now(),
  unique (business_id, id)
);

create index suppliers_business_name_idx
  on public.suppliers (business_id, lower(name));

create table public.investment_adjustments (
  id bigint generated by default as identity primary key,
  business_id uuid not null references public.businesses(id) on delete cascade,
  date date not null,
  amount numeric(12, 2) not null,
  note text not null default '',
  type text not null default 'ajuste' check (type in ('ajuste', 'compra')),
  supplier_id bigint,
  created_at timestamptz not null default now(),
  constraint investment_adjustments_supplier_same_business_fk
    foreign key (business_id, supplier_id)
    references public.suppliers (business_id, id)
    on delete set null (supplier_id)
);

create index investment_adjustments_business_date_id_idx
  on public.investment_adjustments (business_id, date desc, id desc);

alter table public.businesses enable row level security;
alter table public.business_members enable row level security;
alter table public.daily_records enable row level security;
alter table public.suppliers enable row level security;
alter table public.investment_adjustments enable row level security;

create policy "Business members can view their business"
  on public.businesses for select to authenticated
  using (public.is_business_member(id));

create policy "Users can view their own membership"
  on public.business_members for select to authenticated
  using (user_id = (select auth.uid()));

create policy "Business members can access daily records"
  on public.daily_records for all to authenticated
  using (public.is_business_member(business_id))
  with check (public.is_business_member(business_id));

create policy "Business members can access suppliers"
  on public.suppliers for all to authenticated
  using (public.is_business_member(business_id))
  with check (public.is_business_member(business_id));

create policy "Business members can access investment adjustments"
  on public.investment_adjustments for all to authenticated
  using (public.is_business_member(business_id))
  with check (public.is_business_member(business_id));

grant select on public.businesses, public.business_members to authenticated;
grant usage on schema public to authenticated;
grant select, insert, update, delete
  on public.daily_records, public.suppliers, public.investment_adjustments
  to authenticated;
grant usage, select on all sequences in schema public to authenticated;

create or replace function public.investment_balance_totals(target_business_id uuid)
returns table (
  adjustments_total numeric,
  purchases_total numeric,
  invested_total numeric
)
language sql
stable
security invoker
set search_path = ''
as $$
  select
    coalesce((
      select sum(adjustment.amount)
      from public.investment_adjustments as adjustment
      where adjustment.business_id = target_business_id
        and adjustment.type = 'ajuste'
    ), 0)::numeric as adjustments_total,
    coalesce((
      select sum(adjustment.amount)
      from public.investment_adjustments as adjustment
      where adjustment.business_id = target_business_id
        and adjustment.type = 'compra'
    ), 0)::numeric as purchases_total,
    coalesce((
      select sum(record.total_sold * (1 - record.profit_percent))
      from public.daily_records as record
      where record.business_id = target_business_id
    ), 0)::numeric as invested_total
  where public.is_business_member(target_business_id);
$$;

revoke all on function public.investment_balance_totals(uuid) from public;
grant execute on function public.investment_balance_totals(uuid) to authenticated;
